def pages_summary():
    return "\n".join(f"- {n}: {u} — {d}" for n, u, d in PAGES)


def find_topic(query):
    q = re.sub(r"\s+", " ", (query or "").lower())
    best, score = None, 0
    for key, (title, _url, _steps) in GUIDE.items():
        words = (title + " " + _ALIASES.get(key, "")).lower().split()
        s = sum(1 for w in words if len(w) > 1 and w in q)
        if s > score:
            best, score = key, s
    return best


def render_topic(key):
    title, url, steps = GUIDE[key]
    body = "\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1))
    return f"{title}:\n{body}", url


def topics_list():
    return "، ".join(f"{k} ({v[0]})" for k, v in GUIDE.items())
